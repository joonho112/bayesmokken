#' Scientific Reasoning Scale responses (Italian sample)
#'
#' Responses of 337 Italian adults to the 11 dichotomous items of the
#' Scientific Reasoning Scale. This is the dataset used in the empirical
#' application of the binary method implemented here, and it is the fastest way
#' to see the package working on real data.
#'
#' The scale is scored so that 1 marks the answer keyed as scientifically
#' correct. Items are stored in the fixed order `SRS1` through `SRS11`; that
#' order is part of the analysis contract of the published application, which
#' forbids item deletion, reversal and reselection, so treat the eleven columns
#' as one fixed scale rather than a pool to select from.
#'
#' @section Sampling caveats:
#' The 337 rows are a complete-case subset of 606 consent-eligible
#' respondents, recruited by snowball sampling. That is a nonprobability
#' design, so descriptive statements about a wider Italian population are not
#' supported by it. The package's intervals describe sampling uncertainty
#' under a working independent-respondent assumption; no recruiter or network
#' identifier is available, so clustering induced by snowball recruitment
#' cannot be adjusted for.
#'
#' @format A data frame with 337 rows and 11 integer columns, each 0 or 1.
#'   Row names are the original respondent identifiers.
#' \describe{
#'   \item{SRS1}{First item of the Scientific Reasoning Scale, 0 or 1.}
#'   \item{SRS2, SRS3, SRS4, SRS5, SRS6}{Items 2 to 6, 0 or 1.}
#'   \item{SRS7, SRS8, SRS9, SRS10, SRS11}{Items 7 to 11, 0 or 1.}
#' }
#'
#' @source
#' Caliciuri, R., & Lanz, M. (2024). *Psychometric properties of the Scientific
#' Reasoning Scale: Application to the Italian context.* OSF project
#' \url{https://osf.io/jk9dp/}, \doi{10.17605/OSF.IO/JK9DP}.
#' Distributed under CC BY 4.0 and redistributed here with attribution; see
#' `system.file("extdata", "DATA-LICENSES.md", package = "bayesmokken")`.
#'
#' The instrument is due to Drummond, C., & Fischhoff, B. (2017). Development
#' and validation of the Scientific Reasoning Scale. *Journal of Behavioral
#' Decision Making*, 30(1), 26-38. \doi{10.1002/bdm.1906}.
#'
#' Retrieved through the Item Response Warehouse and rebuilt by
#' `data-raw/srs.R`, which verifies the source file against a recorded
#' SHA-256 digest before use.
#'
#' @examples
#' data(srs)
#' dim(srs)
#'
#' # The deterministic coefficient
#' mokken_h(srs)
#'
#' # With its interval (raise `draws` for real work)
#' bb_mokken_h(srs, draws = 200, seed = 1)
#'
#' @family bayesmokken-data
#' @seealso [classroom_wb] for a clustered polytomous example.
"srs"


#' Simulated classroom well-being ratings
#'
#' A fully synthetic dataset of 614 pupils in 30 classrooms answering six
#' five-point items. It exists so that every example, test and vignette that
#' needs clustered polytomous data can run anywhere, with no external
#' dependency.
#'
#' No real pupil contributed to this dataset. It was generated by
#' [bm_simulate()] with a fixed seed; `data-raw/classroom_wb.R` rebuilds it and
#' will fail loudly if the regenerated data lose the property described below.
#'
#' @section Why it is built the way it is:
#' Cluster size is deliberately tied to the classrooms' latent level and
#' spread, so the two population targets this package distinguishes -- the
#' respondent-weighted and the equal-cluster coefficient -- really do differ
#' (about .637 against .622). That difference is the point: with equal-sized
#' clusters, or with size unrelated to level, the choice of target would not
#' matter and there would be nothing to demonstrate.
#'
#' The number of pupils, classrooms, categories and the intraclass correlation
#' are of the same order as the real clustered application discussed in the
#' documentation (`mokken::SWMDK`), so the workflow feels realistic. It is not
#' a model of that study, does not reproduce its item structure, and its
#' coefficient should not be compared with the published one.
#'
#' @format A data frame with 614 rows and 7 columns.
#' \describe{
#'   \item{class_id}{Factor with 30 levels, `class01` to `class30`. Classroom
#'     sizes range from 12 to 29 pupils.}
#'   \item{wb1, wb2, wb3, wb4, wb5, wb6}{Integer item responses on 1 to 5,
#'     higher meaning more agreement. Already scored: no item needs reversing.}
#' }
#'
#' @source Generated by `data-raw/classroom_wb.R` using [bm_simulate()] with
#'   seed 20260810.
#'
#' @examples
#' data(classroom_wb)
#' items <- paste0("wb", 1:6)
#'
#' # Declare the score support once, then reuse it
#' sup <- bm_supports(classroom_wb, items = items)
#'
#' # The respondent-weighted target
#' mokken_h(classroom_wb[, items],
#'          item_type = "ordinal", supports = sup,
#'          cluster = classroom_wb$class_id,
#'          cluster_target = "respondent",
#'          weight_law = "hierarchical_cluster")
#'
#' @family bayesmokken-data
#' @seealso [bm_simulate()] for the generator, [srs] for real binary data.
"classroom_wb"
